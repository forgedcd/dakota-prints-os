import { chromium } from 'playwright';
const BASE = 'http://localhost:5055';
const OUT = '/home/user/workspace/dakota-prints-admin-os/qa-screens';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 375, height: 900 } });
p.setDefaultTimeout(15000);
await p.goto(`${BASE}/#/login`, { waitUntil: 'networkidle' });
await p.fill('input[type="email"]', 'admin@dakotaprints.com');
await p.fill('input[type="password"]', 'ForgedOS2026!');
await p.click('button:has-text("Sign in")');
await p.waitForTimeout(1200);
await p.goto(`${BASE}/#/products`, { waitUntil: 'networkidle' });
await p.waitForTimeout(600);
await p.locator('input.field').first().fill('Stapled Ticket Books — Black');
await p.waitForTimeout(700);
const card = p.locator('text=Stapled Ticket Books').first().locator('xpath=ancestor::li[1]');
await card.waitFor({ state: 'visible', timeout: 10000 });
await card.locator('button:has-text("Edit")').click();
await p.waitForTimeout(600);
await p.locator('button:has-text("Pricing")').first().click();
await p.waitForTimeout(900);
const heading = p.locator('text=Price grid').first();
await heading.scrollIntoViewIfNeeded();
await p.waitForTimeout(300);
const grids = p.locator('.scroll-x.rounded-lg, .rounded-lg.scroll-x');
const target = p.locator('div.rounded-lg.border.border-ink-100.scroll-x, div.scroll-x.rounded-lg.border').first();
// use the 3rd matched .scroll-x (index 2) which is the first grid table
const el = p.locator('.scroll-x').nth(2);
await el.evaluate(node => node.scrollTo({ left: 999, behavior: 'instant' }));
await p.waitForTimeout(300);
await p.screenshot({ path: `${OUT}/04f-matrix-grid-scrolled-max-mobile.png` });
await b.close();
console.log('done');
